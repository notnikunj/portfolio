"""
Turns the hand-drawn self-portrait into data the site can use.

Outputs
  src/data/portrait.js          ~N points sampled along the gold strokes, normalised
                                to [-1, 1] (y down). The "About" cluster morphs into these.
  public/images/portrait.png    the drawing cropped, on a transparent background.
  public/favicon.png            32 x 32 icon (face crop)
  public/apple-touch-icon.png   180 x 180 icon (face crop, on the site's ground colour)

Run from the project root (only needed if you change the drawing):
  python3 scripts/extract_portrait.py
Requires: pip install pillow numpy
"""
import json
import random
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "scripts" / "portrait-source.png"
N_POINTS = 460
MIN_DIST = 7  # px in source image, keeps points evenly spread along strokes
GROUND = (28, 28, 27)

img = Image.open(SRC).convert("RGB")
a = np.asarray(img).astype(int)
r, g, b = a[..., 0], a[..., 1], a[..., 2]
# gold strokes: clearly warmer and brighter than the dark ground
mask = (r > 120) & (g > 90) & (b < 120) & (r - b > 60)

ys, xs = np.nonzero(mask)
x0, x1, y0, y1 = xs.min(), xs.max(), ys.min(), ys.max()
pad = 24
x0, y0 = max(0, x0 - pad), max(0, y0 - pad)
x1, y1 = min(a.shape[1] - 1, x1 + pad), min(a.shape[0] - 1, y1 + pad)

# --- points -----------------------------------------------------------------
random.seed(7)
coords = list(zip(xs.tolist(), ys.tolist()))
random.shuffle(coords)
picked = []
grid = {}
cell = MIN_DIST
for (x, y) in coords:
    gx, gy = x // cell, y // cell
    ok = True
    for dx in (-1, 0, 1):
        for dy in (-1, 0, 1):
            for (px, py) in grid.get((gx + dx, gy + dy), ()):
                if (px - x) ** 2 + (py - y) ** 2 < MIN_DIST ** 2:
                    ok = False
                    break
            if not ok:
                break
        if not ok:
            break
    if ok:
        picked.append((x, y))
        grid.setdefault((gx, gy), []).append((x, y))

# thin to N_POINTS, evenly
random.shuffle(picked)
picked = picked[:N_POINTS]
cx, cy = (xs.min() + xs.max()) / 2, (ys.min() + ys.max()) / 2
half = max(xs.max() - xs.min(), ys.max() - ys.min()) / 2
pts = [[round((x - cx) / half, 4), round((y - cy) / half, 4)] for (x, y) in picked]
pts.sort(key=lambda p: (p[1], p[0]))

out = ROOT / "src" / "data" / "portrait.js"
out.write_text(
    "// Generated by scripts/extract_portrait.py from Nikunj's hand-drawn self-portrait.\n"
    "// Points along the strokes, normalised to [-1, 1] (y grows downward). Do not edit by hand.\n"
    f"export const portraitPoints = {json.dumps(pts, separators=(',', ':'))};\n"
)
print(f"{len(pts)} portrait points -> {out.relative_to(ROOT)}")

# --- transparent crop ---------------------------------------------------------
rgba = np.zeros((a.shape[0], a.shape[1], 4), dtype=np.uint8)
# soft alpha from "goldness" so anti-aliased edges stay smooth
gold = np.clip((r - b - 20) * 3, 0, 255)
rgba[..., 0], rgba[..., 1], rgba[..., 2] = 203, 166, 58
rgba[..., 3] = gold.astype(np.uint8)
crop = Image.fromarray(rgba, "RGBA").crop((x0, y0, x1, y1))
w = 520
crop = crop.resize((w, round(crop.height * w / crop.width)), Image.LANCZOS)
crop.save(ROOT / "public" / "images" / "portrait.png", optimize=True)
print("portrait.png", crop.size)

# --- icons (face only: glasses region) ---------------------------------------
face = Image.fromarray(rgba, "RGBA").crop((560, 160, 1200, 1060))
side = max(face.size)
sq = Image.new("RGBA", (side, side), GROUND + (255,))
sq.alpha_composite(face, ((side - face.width) // 2, (side - face.height) // 2))
sq.convert("RGB").resize((180, 180), Image.LANCZOS).save(ROOT / "public" / "apple-touch-icon.png", optimize=True)
sq.resize((32, 32), Image.LANCZOS).save(ROOT / "public" / "favicon.png", optimize=True)
print("icons written")
